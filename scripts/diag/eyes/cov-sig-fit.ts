// QB lane 2026-11-18: his learned picture of each coverage after the snap (qbmind.ts POST_SIG, docs/reviews/
// 2026-11-18-coverage-certainty.md). From his own looks only: QBMind.postFeaturesObserved() on his memory (his delayed,
// noisy pictures, filled where his eyes went), never true defender state. Per coverage, at 0.5 / 0.8 / 1.2 s after the
// snap: the mean and the spread (sd) of [defenders heading deep, middle of the field closed, coverage players turned].
// Staged plays (every coverage; formations, concepts, rosters, seeds, flips varied) and league games (the formations and
// calls a passer meets) are pooled.
//   node --import tsx scripts/diag/eyes/cov-sig-fit.ts [games] > src/sim/coverage-signatures.ts
// Re-run when the defense changes; test/coverage-signatures.test.ts fails when a coverage drifts outside its template.
import { Rng } from '../../../src/core/rng.js';
import { simulateGame } from '../../../src/game/game.js';
import { generateTeam, leagueSample } from '../../../src/league/team.js';
import { COVERAGES } from '../../../src/playbook/defense.js';
import { PlaySim } from '../../../src/sim/playsim.js';
import { nativeTraceSetup } from '../command-trace.js';

const TIMES = [0.5, 0.8, 1.2];
const games = Number(process.argv[2] ?? 4);
const rows = new Map<string, number[][][]>(); // coverage -> time index -> samples of [deep, mof, turned]
const push = (cov: string, k: number, f: number[]) => {
  const r = rows.get(cov) ?? TIMES.map(() => [] as number[][]); rows.set(cov, r); r[k].push(f);
};
/** Record his observed features at each time on one play (until the throw, or the last time). */
function sample(sim: any, cov: string, maxTicks = 40) {
  const seen = new Set<number>();
  for (let i = 0; i < maxTicks && sim.phase === 'live'; i++) {
    sim.tick();
    for (let k = 0; k < TIMES.length; k++) if (!seen.has(k) && Math.abs(sim.t - TIMES[k]) < 0.026) {
      seen.add(k); push(cov, k, sim.qbMind.postFeaturesObserved());
    }
    if (seen.size === TIMES.length || sim.ball.kind === 'air') break;
  }
}

// Staged: every coverage, 24 plays each.
const FORMS = ['gun_doubles_11', 'gun_trips_11', 'ace_12', 'gun_empty_11', 'gun_bunch_11', 'ace_11', 'pistol_12', 'i_pro_21'];
const CONCEPTS = ['curl_flat', 'smash', 'four_verts', 'mesh', 'dagger', 'slant_flat'];
for (const c of COVERAGES) for (let i = 0; i < 24; i++) {
  let sim: any;
  try { sim = new PlaySim(nativeTraceSetup({ coverage: c.id, concept: CONCEPTS[i % CONCEPTS.length], formation: FORMS[(i * 5) % FORMS.length], roster: 1 + (i % 12), seed: 1 + Math.floor(i / 6), flip: i % 2 === 1 })); }
  catch { continue; }
  sample(sim, c.id);
}

// League: pass plays as called in games.
const orig = PlaySim.prototype.run;
PlaySim.prototype.run = function (this: any) {
  const sim: any = this;
  if (!sim.isPass || !sim.defCall?.coverage) return orig.apply(this);
  const tick0 = sim.tick.bind(sim), seen = new Set<number>();
  sim.tick = () => { tick0(); for (let k = 0; k < TIMES.length; k++) if (!seen.has(k) && sim.ball.kind !== 'air' && Math.abs(sim.t - TIMES[k]) < 0.026) { seen.add(k); push(sim.defCall.coverage.id, k, sim.qbMind.postFeaturesObserved()); } };
  return orig.apply(this);
};
for (let g = 0; g < games; g++) {
  const seed = 201 + g, rng = new Rng(seed);
  const home = generateTeam(rng, 'Ironmen', 'IRN', { strength: 0.55 }), away = generateTeam(rng, 'Comets', 'COM', { strength: 0.55 });
  simulateGame(leagueSample(home, seed), leagueSample(away, seed), { seed });
}

const out: Record<string, { n: number[]; mean: number[][]; sd: number[][] }> = {};
for (const c of COVERAGES) {
  const r = rows.get(c.id); if (!r) continue;
  const stat = (xs: number[][], j: number) => { const v = xs.map((x) => x[j]); const m = v.reduce((s, x) => s + x, 0) / v.length;
    return { m, sd: Math.sqrt(v.reduce((s, x) => s + (x - m) ** 2, 0) / Math.max(1, v.length - 1)) }; };
  out[c.id] = { n: r.map((xs) => xs.length),
    mean: r.map((xs) => [0, 1, 2].map((j) => +stat(xs, j).m.toFixed(3))),
    sd: r.map((xs) => [0, 1, 2].map((j) => +stat(xs, j).sd.toFixed(3))) };
}
process.stdout.write(`/** His learned post-snap picture of each coverage (QBMind.postSnapRead), fitted from his own looks: generated by
 * scripts/diag/eyes/cov-sig-fit.ts (staged plays for every coverage, plus ${games} league games), ${new Date().toISOString().slice(0, 10)}. Do not edit by hand; re-run
 * the script when the defense changes (test/coverage-signatures.test.ts fails when a coverage drifts outside it).
 * Per coverage, at TIMES s after the snap: the mean and sd of [defenders heading deep, middle closed, players turned],
 * and the number of looks. */
export const SIG_TIMES = ${JSON.stringify(TIMES)};
export const COVERAGE_SIGNATURES: Record<string, { n: number[]; mean: number[][]; sd: number[][] }> = ${JSON.stringify(out, null, 1)};
`);

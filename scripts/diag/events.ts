import { Rng } from '../../src/core/rng.js';
import { HASH_LEFT_Y } from '../../src/core/field.js';
import { generateTeam, pickDefense, pickOffense } from '../../src/league/team.js';
import { PASS_BY_ID } from '../../src/playbook/concepts.js';
import { COVERAGE_BY_ID, FRONT_BY_ID } from '../../src/playbook/defense.js';
import { FORMATION_BY_ID } from '../../src/playbook/formations.js';
import { PlaySim } from '../../src/sim/playsim.js';
const [cid, cov, seed] = process.argv.slice(2);
const rng = new Rng(5);
const off = generateTeam(rng, 'O', 'OFF', { strength: 0.55 });
const def = generateTeam(rng, 'D', 'DEF', { strength: 0.55 });
const formation = FORMATION_BY_ID.gun_doubles_11;
const sim = new PlaySim({ offense: pickOffense(off, formation.personnel), defense: pickDefense(def, 'nickel'), offCall: { formation, flip: false, kind: 'pass', pass: PASS_BY_ID[cid], label: cid }, defCall: { personnel: 'nickel', front: FRONT_BY_ID.over, coverage: COVERAGE_BY_ID[cov], pressure: null, label: '' }, los: 35, ballY: HASH_LEFT_Y, firstDownX: 45, seed: Number(seed) });
const r = sim.run();
for (const e of r.events) console.log(e.t.toFixed(2), e.type, e.a !== undefined ? sim.agents[e.a].slot : '', e.b !== undefined ? sim.agents[e.b].slot : '', e.note ?? '');
console.log('yards', r.yards.toFixed(1), 'yac', r.stats.yac?.toFixed(1), 'missed', r.stats.missedTackles, 'broken', r.stats.brokenTackles);
